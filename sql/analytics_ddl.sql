-- ============================================================================
-- DDL: analytics.fact_orders
-- Granularity: One row per unique order.
-- ============================================================================

DROP TABLE IF EXISTS analytics.fact_orders CASCADE;

CREATE TABLE analytics.fact_orders (
    -- Surrogate Key (Fact Primary Key)
    order_sk                    BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    -- Business / Natural Key
    order_id                    INTEGER NOT NULL,

    -- Dimension Foreign Keys
    customer_sk                 INTEGER NOT NULL,
    order_date_key              INTEGER NOT NULL,
    shipped_date_key            INTEGER,
    delivered_date_key          INTEGER,

    -- Degenerate Dimensions (Transactional Attributes)
    order_status                VARCHAR(50) NOT NULL,
    payment_method              VARCHAR(50) DEFAULT 'Unknown',
    discount_code               VARCHAR(50),

    -- Geographic Snapshot at Time of Order
    shipping_city               VARCHAR(100),
    shipping_state              VARCHAR(100),
    shipping_country            VARCHAR(10) DEFAULT 'US',

    -- Actual Timestamp Fields
    order_date                  DATE,
    shipped_date                DATE,
    delivered_date              DATE,

    -- Pre-calculated Logistics Lifecycle Metrics
    fulfillment_lead_days       INTEGER, -- shipped_date - order_date
    delivery_transit_days       INTEGER, -- delivered_date - shipped_date
    total_fulfillment_days      INTEGER, -- delivered_date - order_date

    -- Warehouse Lineage
    dwh_created_at              TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    -- Referential Integrity Constraints
    CONSTRAINT fk_fact_orders_customer
        FOREIGN KEY (customer_sk) REFERENCES analytics.dim_customers (customer_sk),

    CONSTRAINT fk_fact_orders_order_date
        FOREIGN KEY (order_date_key) REFERENCES analytics.dim_date (date_key),

    CONSTRAINT fk_fact_orders_shipped_date
        FOREIGN KEY (shipped_date_key) REFERENCES analytics.dim_date (date_key),

    CONSTRAINT fk_fact_orders_delivered_date
        FOREIGN KEY (delivered_date_key) REFERENCES analytics.dim_date (date_key),

    CONSTRAINT uq_fact_orders_order_id UNIQUE (order_id)
);

-- Foreign Key B-Tree Indexes for Fast Joins
CREATE INDEX idx_fact_orders_customer_sk ON analytics.fact_orders (customer_sk);
CREATE INDEX idx_fact_orders_order_date_key ON analytics.fact_orders (order_date_key);


-- ============================================================================
-- DDL: analytics.fact_order_items
-- Granularity: One row per unique product item on an order.
-- ============================================================================

DROP TABLE IF EXISTS analytics.fact_order_items CASCADE;

CREATE TABLE analytics.fact_order_items (
    -- Surrogate Key (Line Item Primary Key)
    order_item_sk               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    -- Business Keys
    order_item_id               INTEGER NOT NULL,
    order_id                    INTEGER NOT NULL,

    -- Dimension Foreign Keys
    order_sk                    BIGINT NOT NULL,
    product_sk                  INTEGER NOT NULL,

    -- Order Item Measures (Cleaned from staging text/floats)
    quantity                    INTEGER NOT NULL,
    unit_price                  NUMERIC(12, 2) NOT NULL,
    discount_amount             NUMERIC(12, 2) DEFAULT 0.00,
    gross_amount                NUMERIC(12, 2) NOT NULL, -- quantity * unit_price
    net_amount                  NUMERIC(12, 2) NOT NULL, -- gross_amount - discount_amount

    -- Warehouse Lineage
    dwh_created_at              TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    -- Referential Integrity Constraints
    CONSTRAINT fk_fact_items_order
        FOREIGN KEY (order_sk) REFERENCES analytics.fact_orders (order_sk)
        ON DELETE CASCADE,

    CONSTRAINT fk_fact_items_product
        FOREIGN KEY (product_sk) REFERENCES analytics.dim_products (product_sk)
);

-- Foreign Key Indexes for Fast Aggregations
CREATE INDEX idx_fact_items_order_sk ON analytics.fact_order_items (order_sk);
CREATE INDEX idx_fact_items_product_sk ON analytics.fact_order_items (product_sk);

